inline ITEM* At(unsigned slot) {
 if(!CharacterMachine || !g_pMyInventory)return nullptr;
 if(slot<MAX_EQUIPMENT_INDEX)return &CharacterMachine->Equipment[slot];
 if(slot>=236 && slot<243)return CharacterMachine->GetOnlyEquipment(slot);
 if(slot<MAX_MY_INVENTORY_INDEX)return g_pMyInventory->FindItem(slot-MAX_EQUIPMENT_INDEX);
 if(!g_pNewUISystem)return nullptr;
 if(slot>=WarehouseBase && slot<WarehouseBase+240 && g_pStorageInventory && g_pNewUISystem->IsVisible(SEASON3B::INTERFACE_STORAGE)) {
  for(int page=0;page<MAX_WHAREHOUSE_EXPANSION;++page) {
   auto ctrl=g_pStorageInventory->GetInventoryCtrl(page);if(!ctrl)continue;
   const unsigned base=g_pStorageInventory->GetSourceStorage(0,ctrl);
   const unsigned local=slot-WarehouseBase;
   if(local>=base && local<base+120) {ITEM* item=ctrl->FindItem(local-base);if(item)return item;}
  }
 }
 if(slot>=TradeOwnBase && slot<TradeOtherBase+32 && g_pTrade && g_pNewUISystem->IsVisible(SEASON3B::INTERFACE_TRADE)) {
  auto ctrl=slot<TradeOtherBase?g_pTrade->GetMyInvenCtrl():g_pTrade->GetYourInvenCtrl();
  return ctrl?ctrl->FindItem(slot-(slot<TradeOtherBase?TradeOwnBase:TradeOtherBase)):nullptr;
 }
 if(slot>=PersonalOwnBase && slot<PersonalOwnBase+32 && g_pMyShopInventory && g_pNewUISystem->IsVisible(SEASON3B::INTERFACE_MYSHOP_INVENTORY)) {
  auto ctrl=g_pMyShopInventory->GetInventoryCtrl();return ctrl?ctrl->FindItem(slot-PersonalOwnBase):nullptr;
 }
 if(slot>=PersonalOtherBase && slot<PersonalOtherBase+32 && g_pPurchaseShopInventory && g_pNewUISystem->IsVisible(SEASON3B::INTERFACE_PURCHASESHOP_INVENTORY)) {
  auto ctrl=g_pPurchaseShopInventory->GetInventoryCtrl();return ctrl?ctrl->FindItem(slot-PersonalOtherBase):nullptr;
 }
 if(slot>=ShopBase && slot<ShopBase+120 && g_pNPCShop && g_pNewUISystem->IsVisible(SEASON3B::INTERFACE_NPCSHOP)) {
  auto ctrl=g_pNPCShop->GetInventoryCtrl();return ctrl?ctrl->FindItem(slot-ShopBase):nullptr;
 }
 return nullptr;
}
inline int Slot(ITEM* item) {
 if(!item)return -1;
 for(unsigned s=0;s<MAX_MY_INVENTORY_INDEX;++s)if(At(s)==item)return static_cast<int>(s);
 const unsigned bases[]={236,WarehouseBase,TradeOwnBase,TradeOtherBase,ShopBase,PersonalOwnBase,PersonalOtherBase};
 const unsigned sizes[]={7,240,32,32,120,32,32};
 for(unsigned k=0;k<7;++k)for(unsigned s=0;s<sizes[k];++s)if(At(bases[k]+s)==item)return static_cast<int>(bases[k]+s);
 return -1;
}
// Stable local identity: key is generated by the item manager, never treated
// as the server serial. Copies are used only for identity checks, not rendering.
inline bool Same(const ITEM& a,const ITEM& b) {
 return a.Key==b.Key && a.Type==b.Type && a.Level==b.Level && a.Option1==b.Option1 &&
 a.ExtOption==b.ExtOption && a.PvpTierLevel==b.PvpTierLevel && a.option_380==b.option_380 &&
 a.Jewel_Of_Harmony_Option==b.Jewel_Of_Harmony_Option && a.Jewel_Of_Harmony_OptionLevel==b.Jewel_Of_Harmony_OptionLevel &&
 memcmp(a.bySocketOption,b.bySocketOption,sizeof(a.bySocketOption))==0;
}
inline int ContextOwner(unsigned slot) {
 return slot>=PersonalOtherBase && slot<PersonalOtherBase+32 && g_pPurchaseShopInventory?g_pPurchaseShopInventory->GetShopCharacterIndex():-1;
}
struct View {
 struct Cached {ITEM identity;unsigned slot;int owner;DWORD stamp;Message response;};
 std::vector<Cached> history;
 ITEM* unsupported=nullptr;DWORD unsupportedKey=0,unsupportedTick=0;int unsupportedType=-1;
 int contextOwner=-1;
 Message request,response;ITEM identity{};DWORD sent=0,next=0,received=0;bool active=false,ready=false,waiting=false;
 void Reset(bool keepHistory=false){active=false;ready=false;waiting=false;unsupported=nullptr;if(!keepHistory)history.clear();} // Preserve nonce across connection changes.
 bool Inspect(ITEM* item,Message& out) {
  if(!item){Reset(true);return false;}
  if(unsupported==item && unsupportedKey==item->Key && unsupportedType==item->Type && GetTickCount()-unsupportedTick<250)return false;
  const int slot=(active && At(request.slot)==item)?static_cast<int>(request.slot):Slot(item);if(slot<0 || item->Type<0){Reset();unsupported=item;unsupportedKey=item->Key;unsupportedType=item->Type;unsupportedTick=GetTickCount();return false;}
  if(!active || request.slot!=slot || contextOwner!=ContextOwner(slot) || !Same(identity,*item)) {
   Reset(true);active=true;contextOwner=ContextOwner(slot);identity=*item;request=Message();request.slot=static_cast<std::uint16_t>(slot);request.itemId=item->Type;sent=0;
   for(const auto& cached:history)if(cached.slot==request.slot && cached.owner==contextOwner && Same(cached.identity,*item) && GetTickCount()-cached.stamp<=15000u){response=cached.response;received=cached.stamp;ready=true;break;}
  }
  // Keep the last valid response visible during a background refresh.

  const DWORD now=GetTickCount();
  if(!sent || now-sent>=(waiting?(ready?5000u:750u):ready?2000u:750u)) {
   if(++next==0)++next;request.token=next;sent=now;waiting=true;
   if(!IndependentTierRequestSender::Send(request))waiting=false;
  }
  if(ready && now-received<=15000u){out=response;return response.status==Status::Found || (response.status==Status::Legacy && (response.scoreValid || !response.metadata.options.empty()));}
  return false;
 }
 void Receive(const BYTE* bytes,int size) {
  Message reply;if(size<0 || !Decode(bytes,static_cast<std::size_t>(size),reply) || !active || !Matches(request,reply))return;
  ITEM* current=At(request.slot);
  if(!current || contextOwner!=ContextOwner(request.slot) || !Same(identity,*current) ){Reset();return;}
  waiting=false; if(GetTickCount()-sent>5000 || reply.status==Status::Pending)return;
  response=reply;received=GetTickCount();ready=true;
  for(auto it=history.begin();it!=history.end();)if(it->slot==request.slot && it->owner==contextOwner)it=history.erase(it);else ++it;
  if(history.size()>=64)history.erase(history.begin());
  history.push_back({identity,request.slot,contextOwner,received,response});
 }
};
inline View& Get(){static View v;return v;}
inline int ExcellentBit(WORD option) {
 switch(option) {
 case AT_IMPROVE_LIFE:case AT_EXCELLENT_DAMAGE:return 5;
 case AT_IMPROVE_MANA:case AT_IMPROVE_DAMAGE_LEVEL:case AT_IMPROVE_MAGIC_LEVEL:return 4;
 case AT_DECREASE_DAMAGE:case AT_IMPROVE_DAMAGE_PERCENT:return 3;
 case AT_REFLECTION_DAMAGE:case AT_IMPROVE_ATTACK_SPEED:return 2;
 case AT_IMPROVE_BLOCKING_PERCENT:case AT_IMPROVE_GAIN_LIFE:return 1;
 case AT_IMPROVE_GAIN_GOLD:case AT_IMPROVE_GAIN_MANA:return 0;
 default:return -1;
 }
}
